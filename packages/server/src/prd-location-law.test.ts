type MilestoneState = 'open' | 'closed'
interface ManifestEntry {
  state: MilestoneState
  closedAt: string | undefined
}
interface Manifest {
  generatedAt: string | undefined
  entries: Map<string, ManifestEntry>
}

const GENERATED_AT_RE = /^#\s*generated-at:\s*(\S+)\s*$/m
/**
 * `\r?$` is the blocker fix, not decoration: `.swarm/prd-milestones.txt` is read with
 * `split('\n')`, so on a CRLF checkout every line arrives ending `\r`. `\S` cannot match
 * `\r`, so `$` was unreachable and EVERY row silently failed to match — `parseManifest`
 * returned an empty map and {@link violationsIn} reported NO violations while a
 * closed-milestone PRD sat on the live shelf. Verified on a CRLF copy: 0 rows parsed,
 * the law green on a real violation. `.gitattributes` now pins `.swarm/*.txt` to `eol=lf`
 * so the bytes are right in the first place; this tolerates the `\r` anyway, because a
 * law that goes VACUOUS rather than red is the one failure mode worth belt-and-braces.
 * Only `\r` is tolerated, deliberately — arbitrary trailing whitespace would also accept
 * a row a corrupt generator wrote, which {@link unmappedLiveShelf} must be able to see.
 */
const MANIFEST_ROW_RE = /^(\d+)\t(open|closed)\t(\S+)\r?$/

/** Pure: parses the manifest format `scripts/dev/prd-milestones.sh` writes. A line that is not a comment and does not match the row shape is silently skipped, matching `.swarm/coupling.txt`'s own "blank/comment lines are skipped" convention. */
function parseManifest(text: string): Manifest {
  const generatedAt = GENERATED_AT_RE.exec(text)?.[1]
  const entries = new Map<string, ManifestEntry>()
  for (const line of text.split('\n')) {
    const m = MANIFEST_ROW_RE.exec(line)
    if (!m) continue
    entries.set(m[1]!, { state: m[2] as MilestoneState, closedAt: m[3] === '-' ? undefined : m[3] })
  }
  return { generatedAt, entries }
}

function liveManifest(): Manifest {
  return parseManifest(readFileSync(MANIFEST_PATH, 'utf8'))
}

/** The exact marker {@link declaredExemptionReason} looks for — see the Ruling 2 doc comment above for the form's rationale and its two rejected alternatives. */
const EXEMPTION_MARKER = '**Shelf exemption:**'

/**
 * A declared reason must contain at least this many "words" — runs of 2+ letters — to
 * count as substance rather than a placeholder. A THRESHOLD, not a blacklist of rejected
 * strings ("TBD", "n/a", "-", "x", "**", a bare zero-width space all score 0 or 1): a
 * blacklist is the same fitted instrument this issue already rejects for the exemption
 * itself — the next placeholder is never on the list, and the fix becomes adding a fourth
 * string rather than asking whether ANY placeholder should pass. A single letter, a bare
 * punctuation mark, and an invisible character all score zero because `[A-Za-z]{2,}`
 * requires two-plus letters in a row; a real reason is a sentence, which structurally
 * requires several such runs. See the "declaredExemptionReason" describe block below for
 * every scored form, each checked directly.
 */
const MIN_REASON_WORDS = 3

/**
 * The next CommonMark tab stop at or after `col` — tabs advance to the next multiple of 4, never
 * by a flat +4. **Missing entirely was round 2's finding 2 (#484):** the base implementation
 * counted CHARACTERS ("a tab is one guard-firing character, same as 4 spaces"), not COLUMNS, so
 * `> \t` — a literal space, then a tab — read the tab as an automatic 4-column indent regardless of
 * where it actually started. It does not: a tab's width depends on the column it starts from. See
 * {@link stripBlockquoteMarkers} and {@link measureIndent}, the two places this now feeds, and table
 * rows 30-36 for the worked arithmetic.
 */
function nextTabStop(col: number): number {
  return col + (4 - (col % 4))
}

/**
 * Consumes zero or more levels of a CommonMark blockquote marker (up to 3 leading spaces, `>`,
 * then AT MOST one following whitespace CHARACTER — space or tab, consumed WHOLE) from the START of
 * `line`, tracking the ABSOLUTE column reached (tab-stop correct, via {@link nextTabStop}) rather
 * than a character count. Returns the index and column right after the last level consumed, and
 * whether at least one level was found at all.
 *
 * **Round 2 correction (finding 2, #484):** wave 3 first fixed this to consume only one WHITESPACE
 * CHARACTER per level rather than a whole run — correct for a literal space, wrong for a tab, whose
 * column-width is not fixed. The fix is not "count differently for a tab"; it is to stop counting
 * characters at all and track the column a real CommonMark implementation tracks. Consuming the tab
 * character WHOLE, and crediting the marker with wherever that lands (its own next tab stop, not a
 * flat +1), is what shipped: `>` + one tab alone lands the baseline at column 4 (the tab starts at
 * column 1, its own next stop) with nothing left over — a bare `>\t` is a paragraph, not code, and
 * always was; `>` + a literal space + a tab lands the baseline at column 2 (the SPACE is what
 * satisfies the marker, landing on column 2 exactly, same as any other literal space), and the tab
 * is now ordinary CONTENT indentation measured by {@link measureIndent} from that baseline — table
 * rows 30-36 work every case in this class by hand.
 *
 * **It is NOT the entire CommonMark rule, and row 37 is where the two part company.** CommonMark
 * consumes ONE COLUMN of a following tab, not the whole of it, leaving the remainder as ordinary
 * content indentation — spec "Tabs", example 6: `>\t\tfoo` renders as indented code carrying TWO
 * leading spaces, which is only arithmetic if the marker took one column of the first tab and left
 * two behind. Consuming the tab whole hands those columns to the marker instead, so a tab
 * IMMEDIATELY after `>` followed by two or more spaces reads as a paragraph here and as indented
 * code in a renderer. Measured through this reader at the review of #493, and see row 37. The claim
 * narrowed rather than the code changed, deliberately: the divergence is unreachable in this corpus
 * (no PRD on either shelf contains a tab at all, EXECUTED), it fails OPEN in a wave whose other
 * three fail-open gaps are now closed, and partial-tab consumption is a structural change to this
 * instrument rather than a sentence — it belongs with the container tracking and lazy continuation
 * already booked out of this wave, not stapled to it.
 */
function stripBlockquoteMarkers(line: string): { index: number; column: number; quoted: boolean } {
  let index = 0
  let column = 0
  let quoted = false
  for (;;) {
    let i = index
    let col = column
    let spaces = 0
    while (spaces < 3 && line[i] === ' ') {
      i++
      col++
      spaces++
    }
    if (line[i] !== '>') return { index, column, quoted }
    i++
    col++
    if (line[i] === ' ') {
      i++
      col++
    } else if (line[i] === '\t') {
      i++
      col = nextTabStop(col)
    }
    index = i
    column = col
    quoted = true
  }
}

/**
 * Walks past any further leading spaces/tabs from `index`/`column`, continuing the SAME absolute
 * column arithmetic {@link stripBlockquoteMarkers} started, and reports `credit` — the number of
 * COLUMNS gained, which is what CommonMark's "4 or more" indented-code rule actually measures, never
 * a character count. A space always contributes exactly 1; a tab contributes however far it is to
 * its own next stop from wherever it happens to start, which is the entire fix for round 2's finding
 * 2 (#484) — see {@link stripBlockquoteMarkers}'s doc comment and table rows 30-36.
 */
function measureIndent(line: string, index: number, column: number): { index: number; column: number; credit: number } {
  let i = index
  let col = column
  for (;;) {
    if (line[i] === ' ') {
      i++
      col++
      continue
    }
    if (line[i] === '\t') {
      i++
      col = nextTabStop(col)
      continue
    }
    break
  }
  return { index: i, column: col, credit: col - column }
}

/**
 * A fence delimiter line (3+ of the same backtick or tilde). Read after
 * {@link stripBlockquoteMarkers} and {@link measureIndent} have already established that `credit`
 * is under 4 — CommonMark allows a fence opener indented by 0-3 columns relative to its container,
 * the same allowance a paragraph gets, so this regex only ever runs against content that already
 * clears that check. **Applying this regex directly to un-trimmed content was gap 1 (#484): a fence
 * indented 1-3 columns, with no blockquote at all, never matched, so a marker sitting inside it read
 * as a bare top-level declaration.**
 *
 * **A 4-or-more-column-indented run of backticks is NEVER tested against this regex at all (round 2,
 * finding 1, #484) — table rows 9-10.** Once `credit >= 4`, {@link classifyLines} has already
 * classified the WHOLE line as indented code and moved on; CommonMark never treats an indented
 * opener as a fence in the first place; nothing "opens", so there is no fence for a later line to be
 * "inside" — the line right after an indented ``` ``` ``` is an ORDINARY, visible paragraph, read
 * exactly as if the indented line were not there. The base implementation's table said otherwise
 * ("consistent with row 13, not a separate case") — that sentence was wrong, not the code: row 13
 * indents the MARKER (hiding it, correctly); row 9 indents a FENCE-LOOKING line (hiding only ITSELF,
 * with no effect on anything after it). They were never the same case.
 */
const FENCE_OPEN_RE = /^(`{3,}|~{3,})/

/**
 * Replaces the content of every CommonMark inline code span (`` `...` ``, or a longer run of
 * backticks, on a SINGLE line — this file's spans never cross a line break) with a copy that has
 * every `<` neutralized. Used only to decide where a REAL HTML comment can open; the caller must
 * blank matched comments in the ORIGINAL text, never in this masked copy, so a genuine declaration's
 * visible content is never altered by this function itself.
 *
 * **Why:** gap 4b (#484) — a comment-blanking pass with no notion of code spans treats `` `<!--
 * documented here -->` `` (literal comment syntax someone is discussing, not a real comment) exactly
 * like a real one, deletes it, and can convict a real declaration for having "no reason" when the
 * reason was sitting in that span the whole time.
 */
function maskInlineCodeSpans(line: string): string {
  return line.replace(/(`+)([\s\S]*?)\1/g, (_m, ticks: string, inner: string) => ticks + inner.replace(/</g, '\u0000') + ticks)
}

interface ClassifiedLine {
  /**
   * The line's content once every container is peeled off: blockquote markers consumed via
   * {@link stripBlockquoteMarkers}, then any further leading indentation measured via
   * {@link measureIndent} and dropped, provided its `credit` stayed under 4 columns (CommonMark's
   * "still counts as unindented" allowance, measured in COLUMNS — round 2, finding 2, #484 — never
   * in characters). Meaningless (empty) whenever `isCode` is true.
   */
  content: string
  /** True for a fence delimiter, fenced interior, indented-code line, or a line fully inside an HTML comment — a line a declaration can never start OR continue on. */
  isCode: boolean
  /** True when this line carried at least one level of `>` before any stripping — continuation lines must be quoted; the first declaration line itself need not be (table row 1). */
  quoted: boolean
}

/**
 * The single predicate wave 3 exists to build (#484): classifies every line of `text` ONCE, and
 * both the declaration scan and the continuation loop in {@link declaredExemptionReason} read this
 * same array rather than running their own, disagreeing checks. **Gap 3 was exactly that
 * disagreement** — the continuation loop applied no fence or indent check at all, only the
 * declaration line did, so quoted code text after a placeholder reason could clear the substance
 * threshold. There is now nowhere left for the two scans to diverge, because there is only one scan.
 *
 * Indentation is measured in COLUMNS (via {@link stripBlockquoteMarkers} and
 * {@link measureIndent}), not characters — round 2's finding 2 (#484): a bare character count reads
 * a tab as an automatic 4-column indent no matter where it starts, which is only true when nothing
 * has already moved the starting column. Fixing this here, once, is what makes both scans inherit
 * it; a fix that special-cased the four regressed prefixes at either call site would have left the
 * other scan (or the next unlisted prefix) wrong in exactly the way gap 3 already was.
 *
 * **Wave 4 (#459) — the fence grammar and the comment grammar interleave in ONE pass, not two.**
 * Wave 2 through round 2 blanked every real HTML comment in a pass over the WHOLE text, before this
 * loop knew anything about fences (table rows 15-18). That fails in both directions at once, because
 * a fence's own delimiters are exactly as blankable as ordinary prose to a pass that has not yet
 * decided where the fences are:
 *
 * - **Fail closed (table rows 38-40).** A `<!--` that a reader sees INSIDE a fenced code block is
 *   literal fence interior, never a comment opener — the fence takes precedence. The whole-text pass
 *   did not know that, so it opened a "comment" there, and either blanked to EOF (row 38, no closer
 *   anywhere) or found its closer on some later, unrelated line and blanked everything between —
 *   INCLUDING the fence's own closing delimiter (row 40) — leaving the per-line fence tracker with no
 *   closing delimiter to see, so it read every following line as fence interior forever.
 * - **The mirror, guarded against rather than reintroduced.** A previous attempt (`57b69fd3`,
 *   abandoned) fixed the rows above with two independent passes — a code-line mask computed over RAW
 *   text, consumed by a comment segmenter. Both review seats and the orchestrator found this opens the
 *   OTHER direction: a fence- or indent-looking line INSIDE a genuine multi-line comment is real
 *   comment prose, but a mask computed blind to comment state reads it as code and cuts the comment's
 *   span there, exposing whatever the comment was hiding (the sibling-case tests below cover both
 *   directions).
 *
 * CommonMark resolves exactly this interleaving with one left-to-right scan carrying a THIRD state —
 * `normal` / `in-fence` / `in-html-comment` — where a fence may open only when not already inside a
 * comment, and a comment may open only when not already inside a fence, each closing on its own
 * condition. That is what this loop does: `inComment` is checked FIRST, before any fence or indent
 * logic runs, so nothing inside an open comment is ever read as a fence delimiter (protects the
 * mirror direction); and comment-opener detection is reached only AFTER the fence branches have
 * already returned for the line, so nothing inside an open fence is ever read as a comment opener
 * (fixes rows 38-40). Neither grammar is ever resolved blind to the other's current state.
 *
 * See the grammar table above this file's Ruling 2 doc comment for every input row this function is
 * answerable to.
 */
function classifyLines(text: string): ClassifiedLine[] {
  const out: ClassifiedLine[] = []
  let inFence = false
  let fenceChar = ''
  let fenceLen = 0
  let inComment = false
  // Round 2 (#459, review of `ed8d57f4`): true when the PREVIOUS line was open, visible,
  // non-blank content — i.e. an indented-code start would be interrupting it. Reset to false by
  // a blank line, a fence, indented code itself, or comment interior; never by a code-scan alone.
  let inParagraph = false

  for (const raw of text.split('\n')) {
    let line = raw

    if (inComment) {
      // A real HTML comment opened on an earlier line and has not closed yet. Its content is
      // invisible, and — the mirror of the fence rule below — nothing in it can open a fence: a
      // fence- or indent-looking line fully inside a genuine comment stays comment prose, never a
      // delimiter (#459's sibling case). Checked before any bq/fence/indent logic runs at all.
      const closeAt = line.indexOf('-->')
      if (closeAt === -1) {
        out.push({ content: '', isCode: true, quoted: false })
        inParagraph = false
        continue
      }
      inComment = false
      // Blank through the closer; the remainder of the line (if any) re-enters the pipeline below
      // exactly like a fresh line, so a fence or a further comment can still open in it.
      line = ' '.repeat(closeAt + 3) + line.slice(closeAt + 3)
    }

    const bq = stripBlockquoteMarkers(line)
    const indent = measureIndent(line, bq.index, bq.column)
    const content = line.slice(indent.index)

    if (inFence) {
      // Fence interior is always literal text — a `<!--` in here can never open a comment
      // (#459, table rows 38-40): the branch below that would look for one is never reached.
      const close = indent.credit <= 3 ? /^(`+|~+)\s*$/.exec(content) : null
      if (close && close[1]![0] === fenceChar && close[1]!.length >= fenceLen) inFence = false
      out.push({ content: '', isCode: true, quoted: bq.quoted })
      inParagraph = false
      continue
    }

    // Indented code CANNOT INTERRUPT A PARAGRAPH (#459, review of `ed8d57f4`) — a 4+-column
    // indent right after open, visible content is a LAZY CONTINUATION of that content, not a new
    // code block, and CommonMark's own inline grammar still scans it (verified against
    // commonmark.js 0.31.2: an unindented paragraph followed, with no blank line, by a 4-indented
    // `<!--...-->` renders the comment as a real inline HTML comment INSIDE that paragraph, hidden
    // from a reader — not as literal code). A fence can never open at this indent regardless
    // (CommonMark requires <4 columns for a fence opener unconditionally), so that check stays
    // guarded by `indent.credit < 4` either way; only the CODE classification is conditioned on
    // `inParagraph`, and only the comment scan below is what such a line falls through to.
    if (indent.credit >= 4 && !inParagraph) {
      out.push({ content: '', isCode: true, quoted: bq.quoted }) // indented code — gap 2 lives here
      inParagraph = false
      continue
    }
    if (indent.credit < 4) {
      const open = FENCE_OPEN_RE.exec(content)
      if (open) {
        inFence = true
        fenceChar = open[1]![0]!
        fenceLen = open[1]!.length
        out.push({ content: '', isCode: true, quoted: bq.quoted }) // fence open — gap 1 lives here
        inParagraph = false
        continue
      }
    }

    // Not fenced, not indented code: a real HTML comment may open here, code-span aware (gap 4b)
    // and reaching to EOF when unterminated (gap 4a) — one line at a time, so an opener that
    // outlives this line is picked up by the `inComment` branch above on the next iteration. A
    // paragraph-continuation line whose OWN indent is 4+ columns falls through to here too (the
    // paragraph-interruption fix above), never through the fence-open branch — see that branch's
    // `indent.credit < 4` guard.
    const masked = maskInlineCodeSpans(content)
    let visible = ''
    let cursor = 0
    for (;;) {
      const openAt = masked.indexOf('<!--', cursor)
      if (openAt === -1) {
        visible += content.slice(cursor)
        break
      }
      visible += content.slice(cursor, openAt)
      const closeAt = masked.indexOf('-->', openAt + 4)
      if (closeAt === -1) {
        visible += ' '.repeat(content.length - openAt)
        inComment = true
        cursor = content.length
        break
      }
      visible += ' '.repeat(closeAt + 3 - openAt)
      cursor = closeAt + 3
    }
    out.push({ content: visible, isCode: false, quoted: bq.quoted })
    inParagraph = visible.trim().length > 0
  }
  return out
}

/**
 * Ruling 2's declared-exemption reader. Keyed on the DECLARATION, never on the document:
 * any text carrying a genuine declaration is exempt, regardless of which file it lives
 * in — this function never sees a filename, only `text`.
 *
 * **Verify review found the first version matched the first OCCURRENCE of
 * {@link EXEMPTION_MARKER}, not the first DECLARATION** (2026-09-14, `c8709751`,
 * two independent seats plus the orchestrator, all EXECUTED): a bare `text.indexOf` sees
 * a marker sitting inside an HTML comment, a fenced or indented code block, or a
 * mid-sentence MENTION (this very file's own "keyed on the `**Shelf exemption:**` marker"
 * sentences, added deliberately to each PRD as a human-readable cross-reference) exactly
 * as readily as a real declaration — concealing a real one behind an HTML comment left the
 * suite green, and mutating `indexOf` to `lastIndexOf` did too, because every one of the
 * four PRDs this wave exempts contains the marker TWICE and no test pinned WHICH occurrence
 * governs.
 *
 * The fix: a declaration is a LINE whose content — read from {@link classifyLines} — starts
 * with the marker and is not code. The scan returns the FIRST such line; a mid-sentence
 * mention never qualifies, because the marker there is not at the start of its line's content.
 *
 * The reason may continue across further blockquote lines the same way it always did, ending
 * at the first blank quoted line, non-quoted line, or **CODE** line (prd56 wave 3, gap 3,
 * #484 — the continuation walk used to run its own quoted-line regex with no fence or indent
 * check at all, so a quoted fenced or indented block after a placeholder reason could clear
 * {@link MIN_REASON_WORDS} on code text alone; it now reads the exact same `ClassifiedLine`
 * array the declaration scan does, so a code line ends the paragraph here too). The collected
 * reason must then clear {@link MIN_REASON_WORDS} or the declaration is a hard stop — a
 * placeholder reason convicts the file rather than leaving the scan to hunt for a better one
 * further down, matching ruling 2's "an empty or placeholder reason is not an exemption"
 * exactly.
 *
 * **Round 2 note (#484): the explicit `if (cont.isCode) break` below is defence-in-depth over
 * an invariant that already holds — every code `ClassifiedLine` carries empty `content`, so the
 * very next check (`cont.content.trim().length === 0`) already ends the paragraph on its own,
 * which is why deleting the `isCode` check leaves this file green — it documents the real reason
 * a code line can never contribute to a reason, rather than being the mechanism that enforces it.
 *
 * CRLF line endings are normalized to `\n` up front (`\r\n?` -> `\n`) rather than stripped
 * line-by-line: this text is scanned by {@link classifyLines} at several different points
 * (fence state, indent state, comment state), and normalizing once, before any of them run,
 * means none of them need their own `\r` case.
 *
 * Returns the trimmed, whitespace-collapsed reason, or `undefined` for no declaration, a
 * below-threshold one, or one that never emerges from a comment/fence/indented block.
 */
function declaredExemptionReason(text: string): string | undefined {
  const lines = classifyLines(text.replace(/\r\n?/g, '\n'))

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i]!
    if (line.isCode) continue
    if (!line.content.startsWith(EXEMPTION_MARKER)) continue

    // A declaration line. Collect its paragraph: the rest of this line, then further quoted
    // lines, stopping at the first blank quoted line, non-quoted line, or code line — all
    // three read off the SAME classified array the declaration line itself came from.
    const paragraph: string[] = [line.content.slice(EXEMPTION_MARKER.length)]
    for (let j = i + 1; j < lines.length; j++) {
      const cont = lines[j]!
      if (cont.isCode) break // gap 3: quoted code ends the paragraph exactly like a blank line does
      if (!cont.quoted) break
      if (cont.content.trim().length === 0) break
      paragraph.push(cont.content)
    }
    const reason = paragraph.join(' ').replace(/\s+/g, ' ').trim()
    const words = reason.match(/[A-Za-z]{2,}/g) ?? []
    return words.length >= MIN_REASON_WORDS ? reason : undefined
  }
  return undefined
}

/** Pure: every shelf entry whose milestone is closed and carries no declared exemption. Mirrors `doc-citation-law.test.ts`'s pattern of a pure detector fed by both the real tree and a synthetic mutation. */
function violationsIn(shelf: readonly ShelfEntry[], manifest: Manifest): string[] {
  const out: string[] = []
  for (const { number, file, text } of shelf) {
    const entry = manifest.entries.get(number)
    if (!entry || entry.state !== 'closed') continue
    if (declaredExemptionReason(text) !== undefined) continue
    out.push(file)
  }
  return out
}

/**
 * PRDs allowed to be on the live shelf with NO manifest row — i.e. genuinely no
 * milestone. Named, never inferred: `violationsIn` treats "no row" as "not a violation",
 * so without this floor a row that is MISSING for any other reason — a manifest that
 * failed to parse, a key spelling the generator never produced, a malformed line
 * silently skipped — is indistinguishable from a legitimate exemption and the law
 * fails OPEN. Adding a PRD here is a decision someone makes on purpose.
 */
const NO_MILESTONE_ALLOWLIST: readonly string[] = ['prd-34-the-doorstep.md']

/** Pure: live-shelf PRDs with no manifest row and no place on the allowlist — the floor under {@link violationsIn}. */
function unmappedLiveShelf(shelf: readonly ShelfEntry[], manifest: Manifest): string[] {
  return shelf
    .filter((e) => !manifest.entries.has(e.number) && !NO_MILESTONE_ALLOWLIST.includes(e.file))
    .map((e) => e.file)
}

/** See the doc comment's staleness section for why this is a bound rather than a CI regeneration diff. */
const MAX_MANIFEST_AGE_DAYS = 14
const DAY_MS = 24 * 60 * 60 * 1000

/** Pure: `undefined`/unparseable dates are stale by definition — a manifest that does not say when it was generated cannot be trusted to be fresh. */
function isManifestStale(generatedAt: string | undefined, now: Date): boolean {
  if (generatedAt === undefined) return true
  const then = new Date(generatedAt).getTime()
  if (Number.isNaN(then)) return true
  const ageDays = (now.getTime() - then) / DAY_MS
  // A FUTURE generated-at is stale, not fresh. A negative age is never greater than
  // the bound, so the naive comparison called a clock-skewed or hand-edited manifest
  // permanently fresh — the one input that disables this check entirely.
  if (ageDays < 0) return true // see isFutureStamped: the caller reports this differently
  return ageDays > MAX_MANIFEST_AGE_DAYS
}

